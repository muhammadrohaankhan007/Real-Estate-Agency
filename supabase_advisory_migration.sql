-- ==============================================================================
-- PRIME TIME REAL ESTATE - ADVISORY & NEWSLETTER MIGRATION
-- Migration: Create advisory_leads & newsletter_subscribers tables
-- ==============================================================================

-- 1. Create advisory_leads table for private client valuation requests
CREATE TABLE IF NOT EXISTS advisory_leads (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name text NOT NULL,
  phone_whatsapp text NOT NULL,
  location_phase text NOT NULL,
  property_type text NOT NULL,
  size_covered text,
  objectives_notes text,
  created_at timestamptz DEFAULT now()
);

-- 2. Create index on advisory_leads for fast lookup
CREATE INDEX IF NOT EXISTS idx_advisory_leads_created ON advisory_leads (created_at DESC);

-- 3. Create newsletter_subscribers table for private briefings
CREATE TABLE IF NOT EXISTS newsletter_subscribers (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email_or_phone text UNIQUE NOT NULL,
  created_at timestamptz DEFAULT now()
);

-- 4. Create index on newsletter_subscribers for lookup and deduplication
CREATE INDEX IF NOT EXISTS idx_newsletter_subscribers_contact ON newsletter_subscribers (email_or_phone);

-- 5. Comments for audit trail
COMMENT ON TABLE advisory_leads IS 'High-net-worth client confidential valuation & advisory requests';
COMMENT ON TABLE newsletter_subscribers IS 'Subscribers to private off-market briefings and market dispatches';
